/**
 * Bundles src/lib/contextBuilder.js (and the JSON data it reads) into a plain
 * Node module the /api/chat function can import. The server then builds BotFolio's
 * fact sheet itself instead of trusting whatever context the browser sends.
 *
 * Runs before every build; the output is committed so the function also works
 * if it is packaged before the build step.
 */
import { build } from 'esbuild';

await build({
  entryPoints: ['src/lib/contextBuilder.js'],
  outfile: 'api/_lib/context.mjs',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  loader: { '.json': 'json' },
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-bot-context.mjs — do not edit by hand.' },
  logLevel: 'warning',
});
console.log('bot context → api/_lib/context.mjs');
